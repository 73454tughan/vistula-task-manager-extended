-- Distributed / Team Project - Advanced Task Manager & Team Collaboration
-- Demonstration database schema (separate from Assignment 1)

-- 1. Parent table: categories (One side of 1:N)
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

-- 2. Child table: tasks (Many side of 1:N)
CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    completed BOOLEAN NOT NULL DEFAULT false,
    category_id BIGINT NOT NULL REFERENCES categories(id)
);

-- 3. Default example categories
INSERT INTO categories (name) VALUES
    ('University'),
    ('Work'),
    ('Personal');

-- 4. Row Level Security (RLS) policies for the demonstration database
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Demo allow all on categories"
    ON categories FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Demo allow all on tasks"
    ON tasks FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

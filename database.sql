-- Distributed / Team Project - Advanced Task Manager & Team Collaboration
-- Demonstration database schema (separate from Assignment 1)

-- 1. Parent table: categories (One side of 1:N)
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

-- 2. Child table: tasks (Many side of 1:N)
CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    completed BOOLEAN NOT NULL DEFAULT false,
    category_id BIGINT NOT NULL REFERENCES categories(id)
);

-- 3. Default example categories
INSERT INTO categories (name) VALUES
